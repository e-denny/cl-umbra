# The phase gates so far (PLAN.md §5).  Each clause is checked, not asserted, and
# a clause with nothing behind it says so instead of passing quietly.
#
# Exit status:
#   0  every clause passed
#   1  a clause failed
#   2  no clause failed, but at least one has nothing behind it yet, so the
#      gate is not met (no clause is in that state today; the machinery stays
#      for the clauses later phases will add)
#
# Clauses:
#   1. the unit suite is green (Rove, nine suites)
#   2. every vendored protocol XML generates Lisp that compiles (69 files)
#   3. demo-globals prints the live session's globals, and they match
#      wayland-info (skipped, not failed, when there is no session)
#   4. the fuzz harness feeds 10^6 random cases through the decoder with no
#      crash, hang, unbounded allocation or descriptor leak
#   5. purity: no libwayland or libwlroots in the loaded image (D1), a standing
#      clause that runs after the phase-1 ones
#
# Phase 1 (server core):
#
#   6. wayland-info -- a real libwayland client -- talks to our server and exits
#      0, sees both demo globals, and the server shuts down cleanly on SIGTERM
#   7. soak: 10k connect/disconnect cycles with flat descriptor count and a flat
#      resident set
#   8. a fuzz *client*: 10^6 adversarial connections; the server must never
#      crash, hang, leak, or answer with a malformed message
#   9. an independent C client binds, destroys and re-binds across versions, and
#      gets the released id back
#
# Phase 2a (shm and the first pixels):
#
#  10. a libwayland shm client draws a known pattern through the headless
#      compositor, gets its frame callback, and the captured frame matches pixel
#      for pixel -- plus a valid PNG screenshot
#
# Phase 3 (xdg-shell toplevels):
#
#  11. weston-simple-shm -- a real xdg-shell client -- binds xdg_wm_base, is
#      configured, acks our serial, commits a buffer and draws; the frame is
#      checked for content inside the window and nothing outside it, ping/pong is
#      answered, and the client is still connected at the end
#  12. seats and input: weston-eventdemo -- a real client -- receives our keymap
#      descriptor and repeat_info, is focused when its window maps (and told it is
#      activated), and prints the keys and pointer events we inject with the right
#      keycodes, coordinates and modifier masks; a libxkbcommon probe parses the
#      keymap we actually sent (no default includes)
#
# Phase 3c (the scene):
#
#  13. two weston-simple-shm windows are placed by the cascade at (0,0) and
#      (32,32), hit testing says which one is under a point, hovering moves the
#      pointer while the click moves the keyboard (and the losing toplevel is
#      configured not activated), both windows are drawn where they were placed,
#      and the cursor's own pixels are composited last at the pointer's position
#
# Phase 3d (grabs and keybindings):
#
#  14. a real client (compiled here, with xdg-shell generated by wayland-scanner)
#      asks to be moved with the serial from a button event we sent; the window
#      follows the pointer, stops on the release and is not moved again; a resize
#      request becomes a configure carrying the size the drag implies; Alt+F1
#      cycles the bottom window to the top and Alt+Esc stops the main loop
#
# Phase 3e (nested):
#
#  16. the tinywl parity script, run twice -- once with tinywl's output in memory
#      and input injected, once nested inside another compositor: a real client
#      maps and is drawn where tinywl places it, a click focuses and typing reaches
#      only the focused window, Alt+left drags it, Alt+right resizes it from the
#      edge, Alt+F1 cycles and Alt+Esc closes the clients and stops the loop, with
#      the client's own WAYLAND_DEBUG stream showing an acked configure
#
#  15. our compositor runs as a client of another compositor, in one image and two
#      sockets: the parent sees a mapped, titled, activated xdg_toplevel; the
#      parent's pixels equal the nested compositor's own target; a pointer motion
#      and a key injected into the *parent* arrive in a weston client inside the
#      nested session at the same coordinates, with the same modifier mask; the
#      parent's keymap descriptor crossed the boundary; teardown removes the
#      parent's window and leaks no descriptors
#
# Logs land in a temporary directory that is printed when something fails.

set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

log_dir="$(mktemp -d "${TMPDIR:-/tmp}/cl-wayland-gate.XXXXXX")"
passed=0
failed=0
skipped=0
todo=0

report() {                              # status name detail
  printf '  %-11s %-24s %s\n' "$1" "$2" "$3"
}

pass() { report PASS "$1" "$2"; passed=$((passed + 1)); }
fail() {
  report FAIL "$1" "$2"
  failed=$((failed + 1))
  printf '               log: %s\n' "$3"
  tail -n 25 "$3" | sed 's/^/               /'
}
skip() { report SKIP "$1" "$2"; skipped=$((skipped + 1)); }
not_implemented() { report 'NOT BUILT' "$1" "$2"; todo=$((todo + 1)); }

gb() {                                  # gb LOGFILE command...
  local log="$1"; shift
  "$@" >"$log" 2>&1
}

printf '\nphase 0 gate: protocol core and a hello-world client\n\n'

# 1. Unit suite ------------------------------------------------------------
if gb "$log_dir/tests.log" "$repo_root/scripts/run-tests.sh"; then
  pass 'unit suite' "$(grep -aE '[0-9]+ suites?,' "$log_dir/tests.log" | tail -n 1)"
else
  fail 'unit suite' 'the Rove suite is not green' "$log_dir/tests.log"
fi

# 2. Every vendored protocol compiles --------------------------------------
if gb "$log_dir/protocols.log" sbcl --non-interactive --no-userinit --no-sysinit \
     "${sbcl_evals[@]}" \
     --eval '(asdf:load-system "cl-wayland-protocols")' \
     --load "$repo_root/scripts/gate-protocols.lisp" \
     --eval '(uiop:quit (if (wayland.gate.protocols:compile-all) 0 1))'; then
  pass 'protocols compile' "$(grep -a 'protocols\? compiled' "$log_dir/protocols.log" | tail -n 1)"
else
  fail 'protocols compile' 'a vendored protocol did not compile' "$log_dir/protocols.log"
fi

# 3. demo-globals against the live session ---------------------------------
wayland_socket() {
  local name="${WAYLAND_DISPLAY:-wayland-0}"
  case "$name" in
    /*) printf '%s\n' "$name" ;;
    *)  printf '%s\n' "${XDG_RUNTIME_DIR:-/nonexistent}/$name" ;;
  esac
}
socket="$(wayland_socket)"
if ! command -v wayland-info >/dev/null 2>&1; then
  skip 'demo-globals' 'wayland-info is not installed, so there is nothing to compare with'
elif [ ! -S "$socket" ]; then
  skip 'demo-globals' "no session at $socket"
elif gb "$log_dir/demo.log" sbcl --noinform --non-interactive --no-userinit --no-sysinit \
       "${sbcl_evals[@]}" \
       --eval '(asdf:load-system "cl-wayland-client/demo")' \
       --eval '(uiop:quit (wayland.client.demo:run :error-stream *error-output*))'; then
  grep -a "^interface: '" "$log_dir/demo.log" > "$log_dir/demo-globals.txt"
  wayland-info 2>/dev/null | grep -a "^interface: '" > "$log_dir/wayland-info.txt"
  if diff -u "$log_dir/wayland-info.txt" "$log_dir/demo-globals.txt" > "$log_dir/demo.diff"; then
    pass 'demo-globals' "$(wc -l < "$log_dir/demo-globals.txt" | tr -d ' ') globals, byte-identical to wayland-info"
  else
    fail 'demo-globals' 'output differs from wayland-info' "$log_dir/demo.diff"
  fi
else
  fail 'demo-globals' 'demo-globals did not exit cleanly' "$log_dir/demo.log"
fi

# 4. Fuzz harness ----------------------------------------------------------
if gb "$log_dir/fuzz.log" "$repo_root/scripts/fuzz.sh" 1000000; then
  pass 'fuzz harness' "$(grep -a '[0-9]* cases:' "$log_dir/fuzz.log" | tail -n 1 | sed 's/^ *//')"
else
  fail 'fuzz harness' 'a fuzz case crashed, hung, leaked or broke an invariant' "$log_dir/fuzz.log"
fi

# 6. wayland-info against our server ---------------------------------------
printf '\nphase 1 gate: server core\n\n'

if gb "$log_dir/wayland-info-server.log" "$repo_root/scripts/wayland-info-server.sh"; then
  pass 'wayland-info vs server' "$(grep -a '^wayland-info: exit' "$log_dir/wayland-info-server.log" | tail -n 1 | sed 's/^wayland-info: //')"
else
  fail 'wayland-info vs server' 'our server did not serve wayland-info' "$log_dir/wayland-info-server.log"
fi

# 7. Soak -------------------------------------------------------------------
if gb "$log_dir/soak.log" "$repo_root/scripts/soak.sh"; then
  pass 'soak' "$(grep -a '^soak: descriptors' "$log_dir/soak.log" | sed 's/^soak: //')"
else
  fail 'soak' 'the server leaked descriptors or memory over 10k connections' "$log_dir/soak.log"
fi

# 8. The peer fuzzer -------------------------------------------------------
if gb "$log_dir/fuzz-client.log" "$repo_root/scripts/fuzz-client.sh" 1000000; then
  pass 'fuzz client' "$(grep -a '^[0-9]* connection' "$log_dir/fuzz-client.log" | sed 's/ fuzzed:.*//') fuzzed, server healthy"
else
  fail 'fuzz client' 'a client made the server crash, hang, leak or answer badly' "$log_dir/fuzz-client.log"
fi

# 9. An independent C client ------------------------------------------------
if gb "$log_dir/c-probe.log" "$repo_root/scripts/c-probe.sh"; then
  pass 'C client' "$(grep -a '^c-probe:' "$log_dir/c-probe.log" | sed 's/^c-probe: //')"
else
  fail 'C client' 'the libwayland client probe failed' "$log_dir/c-probe.log"
fi

# 10. The headless frame -----------------------------------------------------
printf '\nphase 2a gate: shared memory and the first pixels\n\n'

if gb "$log_dir/headless-frame.log" "$repo_root/scripts/headless-frame.sh"; then
  pass 'headless frame' "$(grep -a 'pixel checks passed' "$log_dir/headless-frame.log" | sed 's/^headless-frame: //' | cut -c1-40)"
else
  fail 'headless frame' 'the shm client did not draw what it asked for' "$log_dir/headless-frame.log"
fi

# 11. A real xdg-shell client ------------------------------------------------
printf '\nphase 3 gate: xdg-shell toplevels\n\n'

if gb "$log_dir/xdg-shell.log" "$repo_root/scripts/xdg-shell-gate.sh"; then
  pass 'xdg-shell toplevel' "$(grep -a '^xdg-shell-gate: buffer' "$log_dir/xdg-shell.log" | sed 's/^xdg-shell-gate: //' | cut -c1-44)"
else
  fail 'xdg-shell toplevel' 'weston-simple-shm did not draw through our compositor' "$log_dir/xdg-shell.log"
fi

# 12. Seats and input --------------------------------------------------------
printf '\nphase 3b gate: seats and input\n\n'

if gb "$log_dir/seat.log" "$repo_root/scripts/seat-gate.sh"; then
  pass 'seats and input' "$(grep -a '^seat-gate: seat ' "$log_dir/seat.log" | sed 's/^seat-gate: seat seat0: //')"
else
  fail 'seats and input' 'the real client did not receive the input we injected' "$log_dir/seat.log"
fi

# 13. The scene: placement, hit testing, click to focus, cursor --------------
printf '\nphase 3c gate: the scene, hit testing and a drawn cursor\n\n'

if gb "$log_dir/scene.log" "$repo_root/scripts/scene-gate.sh"; then
  pass 'scene and cursor' "$(grep -a '^scene-gate: cursor' "$log_dir/scene.log" | sed 's/^scene-gate: //' | cut -c1-44)"
else
  fail 'scene and cursor' 'placement, click to focus or the cursor did not work' "$log_dir/scene.log"
fi

# 14. Grabs and keybindings --------------------------------------------------
printf '\nphase 3d gate: grabs and keybindings\n\n'

if gb "$log_dir/grab.log" "$repo_root/scripts/grab-gate.sh"; then
  pass 'grabs and keys' "$(grep -a 'ok   the compositor configured the client' "$log_dir/grab.log" | head -n 1 | sed 's/^ *ok *//' | cut -c1-44)"
else
  fail 'grabs and keys' 'a real client was not moved, resized or out-cycled' "$log_dir/grab.log"
fi

# 15. A nested session --------------------------------------------------------
printf '\nphase 3e gate: a nested session\n\n'

if gb "$log_dir/nested.log" "$repo_root/scripts/nested-gate.sh"; then
  pass 'nested session' "$(grep -a '^pixel grid' "$log_dir/nested.log" | sed 's/^ *//' | cut -c1-44)"
else
  fail 'nested session' 'a client inside a nested session was not drawn or did not get input' "$log_dir/nested.log"
fi

# 16. The tinywl parity script, twice ---------------------------------------
printf '\nphase 3 exit gate: tinywl parity, headless and nested\n\n'

if gb "$log_dir/tinywl.log" "$repo_root/scripts/tinywl-parity.sh"; then
  pass 'tinywl parity' "$(grep -ac '^  ok   ' "$log_dir/tinywl.log") checks in two runs"
else
  fail 'tinywl parity' 'a real client was not placed, focused, typed at, dragged, resized, cycled or quit' "$log_dir/tinywl.log"
fi

# Purity (D1) ---------------------------------------------------------------
if gb "$log_dir/purity.log" "$repo_root/scripts/purity-check.sh"; then
  pass 'purity' 'no libwayland or libwlroots in the image'
else
  fail 'purity' 'the loaded image links a forbidden library' "$log_dir/purity.log"
fi

# Verdict ------------------------------------------------------------------
printf '\n  %d passed, %d failed, %d skipped, %d not built\n' \
       "$passed" "$failed" "$skipped" "$todo"
if [ "$failed" -gt 0 ]; then
  printf '  gate: FAILED\n\n'
  printf '  logs: %s\n\n' "$log_dir"
  exit 1
elif [ "$todo" -gt 0 ]; then
  printf '  gate: NOT MET (%d clause(s) unimplemented)\n\n' "$todo"
  rm -rf "$log_dir"
  exit 2
else
  printf '  gate: PASSED (phase 0, 1, 2a, 3a, 3b, 3c, 3d, 3e and tinywl parity)\n\n'
  rm -rf "$log_dir"
  exit 0
fi
